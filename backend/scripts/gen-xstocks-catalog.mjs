#!/usr/bin/env node
/* Regenerates shared/xstocks-catalog.ts (both backend/ and frontend/ copies)
 * from the official, no-auth xStocks API (docs.xstocks.fi/apis/openapi):
 *   GET https://api.xstocks.fi/api/v2/public/assets?network=Solana&page=N
 *
 * Run from backend/:  node scripts/gen-xstocks-catalog.mjs
 *
 * Gives us every xStock minted on Solana with its real underlying ticker,
 * listing country, exchange, logo and mint. Tradability is NOT snapshotted
 * here — it is decided at runtime from Jupiter liquidity (src/jupiter.ts). */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const API = "https://api.xstocks.fi/api/v2/public/assets";
const here = dirname(fileURLToPath(import.meta.url));
const targets = [resolve(here, "../shared/xstocks-catalog.ts"), resolve(here, "../../frontend/shared/xstocks-catalog.ts")];

const nodes = [];
for (let page = 0; page < 50; page++) {
  const r = await fetch(`${API}?network=Solana&page=${page}&pageSize=100`, { headers: { "User-Agent": "rhea-catalog-gen", Accept: "application/json" } });
  if (!r.ok) throw new Error(`xStocks API ${r.status}: ${(await r.text()).slice(0, 200)}`);
  const d = await r.json();
  nodes.push(...d.nodes);
  if (!d.page?.hasNextPage) break;
}

/* ARCA / BATS list ETFs; NYSE American (AMEX) is mostly small-cap equities. */
const FUND_EXCHANGES = new Set(["ARCA", "BATS"]);
const FUND_NAME = /\b(ETF|Fund|Index|iShares|Vanguard|SPDR|Russell|Small Cap|Bull|CLO|Preferred)\b/;
const slugify = (s) => s.toLowerCase().replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

const entries = nodes.map((a) => {
  const sol = a.deployments.find((d) => d.network === "Solana");
  const country = a.underlying?.listingCountry ?? null;
  const exchange = a.trading?.exchange?.abbreviation ?? null;
  const raw = a.underlyingSymbol || a.symbol.replace(/x$/, "");
  const ticker = country === "HK" && /^\d+$/.test(raw) ? `${raw.padStart(4, "0")}.HK` : raw;
  const name = a.name.replace(/\s+xStock$/i, "");
  return { symbol: a.symbol, name, ticker, slug: slugify(name), mint: sol.address, icon: a.logo, country, exchange, fund: FUND_EXCHANGES.has(exchange) || FUND_NAME.test(name) };
}).sort((x, y) => x.symbol.localeCompare(y.symbol));

/* Share classes share a name (News Corp NWS / NWSA) — disambiguate with the ticker. */
const slugCount = new Map();
for (const e of entries) slugCount.set(e.slug, (slugCount.get(e.slug) ?? 0) + 1);
for (const e of entries) if (slugCount.get(e.slug) > 1) e.slug = `${e.slug}-${slugify(e.ticker)}`;
const dupSlugs = entries.map((e) => e.slug).filter((s, i, arr) => arr.indexOf(s) !== i);
if (dupSlugs.length) throw new Error("duplicate slugs: " + dupSlugs.join(", "));
if (entries.some((e) => !e.mint)) throw new Error("entry without Solana mint");

const j = JSON.stringify;
const lines = entries.map((e) => `  { symbol: ${j(e.symbol)}, name: ${j(e.name)}, ticker: ${j(e.ticker)}, slug: ${j(e.slug)}, mint: ${j(e.mint)}, icon: ${j(e.icon)}, country: ${j(e.country)}, exchange: ${j(e.exchange)}, fund: ${e.fund} },`);
const out = `/* Rhea — full xStocks Solana catalog (GENERATED by backend/scripts/gen-xstocks-catalog.mjs — do not hand-edit).
 *
 * DUPLICATED in frontend/shared/ and backend/shared/ (they deploy separately);
 * the generator writes both copies.
 *
 * Source: official xStocks public API, GET ${API}?network=Solana
 * (no auth; docs.xstocks.fi/apis/openapi). Snapshot ${new Date().toISOString().slice(0, 10)} — ${entries.length} assets.
 * This is the issuer's full issuance list, NOT a tradable list: whether a token
 * is tradable is decided at runtime from Jupiter liquidity (see jupiter.ts). */

export type XStockCatalogEntry = {
  /** Token symbol on Solana, e.g. "NVDAx" */
  symbol: string;
  /** Issuer product name without the " xStock" suffix */
  name: string;
  /** Real underlying ticker, e.g. "NVDA", "BRK.B", "0700.HK" */
  ticker: string;
  /** Slug derived from the name; used as the company id when not curated */
  slug: string;
  /** Solana mint (Token-2022, 8 decimals) */
  mint: string;
  /** Issuer logo URL */
  icon: string;
  /** ISO 3166-1 alpha-2 of the exchange the underlying trades on (null when the issuer has not set it) */
  country: string | null;
  /** Exchange abbreviation, e.g. "NASDAQ", "NYSE", "HKEX", "ARCA" */
  exchange: string | null;
  /** True for ETFs / funds (ARCA or BATS listing, or a fund-like name) */
  fund: boolean;
};

export const XSTOCKS_CATALOG: XStockCatalogEntry[] = [
${lines.join("\n")}
];
`;
for (const t of targets) writeFileSync(t, out);
console.log(`wrote ${entries.length} entries →\n  ${targets.join("\n  ")}`);
